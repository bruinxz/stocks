/**
 * tradingCalendar 时区 bug 回归测试 (2026-06-27 prod 事故)
 *
 * 跑法:
 *   cd backend && npx ts-node --transpile-only tests/utils/tradingCalendar-timezone.test.ts
 *
 * 背景:
 *   原实现 `d.getTime() + 8h - d.getTimezoneOffset() * 60_000` 在 CST 进程上
 *   把周五 16:00+ 误判成周六, 导致 30+ 个 cron 在周五盘后被节假日 guard 错杀.
 *
 * 覆盖矩阵 (用 Date string `YYYY-MM-DDTHH:MM:00+08:00` 锚定 Asia/Shanghai 时刻,
 * 不论 host 进程时区如何结果都应一致):
 *   [1] 周五 09:00 / 12:00 / 15:59 / 16:00 / 16:01 / 17:10 / 18:30 / 22:00 / 23:59 都判周五
 *   [2] 周一 / 周四 同样时段都判工作日
 *   [3] 周六 / 周日 任意时段都判非工作日
 *   [4] 节假日 (端午 2026-06-19) 即便是周五也是 holiday
 *   [5] 跨年: 2026-01-01 (周四元旦) holiday; 2026-12-31 (周四) 工作日
 *   [6] 跨月: 2026-05-31 (周日) 非工作日; 2026-06-01 (周一) 工作日
 *   [7] 闰年类边界: 2028-02-29 是闰年, 应判周二工作日 (本日历未含 2028 数据, 但
 *       weekday 判定不依赖节假日表, 应正确返 true)
 *   [8] explainNonTradeDay 周五任意时段都返 null (是交易日)
 *   [9] ISO date 字符串入参 ("2026-06-26") 与 Date 入参 (周五 22:00) 结果一致
 */
import { isAShareTradeDay, explainNonTradeDay } from '../../src/utils/tradingCalendar';

let pass = 0;
let fail = 0;
const failures: string[] = [];

function assert(cond: boolean, msg: string): void {
  if (cond) pass++;
  else {
    fail++;
    failures.push(msg);
    console.error(`FAIL ${msg}`);
  }
}

function sh(yyyymmdd: string, hhmm = '10:00'): Date {
  return new Date(`${yyyymmdd}T${hhmm}:00+08:00`);
}

// ---------------------------------------------------------------------------
// [1] 周五 (2026-06-26) 各时段都判工作日, 不能在 16:00+ 漂成周六
// ---------------------------------------------------------------------------
console.log('[1] 周五 2026-06-26 全天时段都应是交易日 (旧 bug 在 16:00+ 漂成周六)...');
for (const hhmm of [
  '09:00',
  '12:00',
  '14:00',
  '15:00',
  '15:59',
  '16:00', // 旧 bug 触发点
  '16:01',
  '17:10', // DAILY_UPDATE cron 时段
  '18:00', // SYNC_HISTORY cron
  '18:30', // DATA_FRESHNESS_CHECK cron
  '21:00', // DAILY_HEALTH_REPORT cron
  '22:00',
  '23:59',
]) {
  assert(
    isAShareTradeDay(sh('2026-06-26', hhmm)) === true,
    `周五 2026-06-26 ${hhmm} 应判交易日`
  );
  assert(
    explainNonTradeDay(sh('2026-06-26', hhmm)) === null,
    `周五 2026-06-26 ${hhmm} explainNonTradeDay 应返 null`
  );
}

// ---------------------------------------------------------------------------
// [2] 周一 / 周四 同样时段都判工作日
// ---------------------------------------------------------------------------
console.log('[2] 周一 2026-06-22 / 周四 2026-06-25 全天时段都判工作日...');
for (const day of ['2026-06-22', '2026-06-25']) {
  for (const hhmm of ['09:00', '15:30', '16:00', '17:10', '23:00']) {
    assert(
      isAShareTradeDay(sh(day, hhmm)) === true,
      `${day} ${hhmm} 应判交易日`
    );
  }
}

// ---------------------------------------------------------------------------
// [3] 周六 / 周日 任意时段都判非工作日
// ---------------------------------------------------------------------------
console.log('[3] 周六 2026-06-27 / 周日 2026-06-28 任意时段都判非工作日...');
for (const day of ['2026-06-27', '2026-06-28']) {
  for (const hhmm of ['00:00', '09:30', '12:00', '23:59']) {
    assert(
      isAShareTradeDay(sh(day, hhmm)) === false,
      `${day} ${hhmm} 应判非交易日`
    );
  }
}
assert(
  (explainNonTradeDay(sh('2026-06-27', '10:00')) || '').includes('周六'),
  '周六 explain 应含 "周六"'
);
assert(
  (explainNonTradeDay(sh('2026-06-28', '10:00')) || '').includes('周日'),
  '周日 explain 应含 "周日"'
);

// ---------------------------------------------------------------------------
// [4] 节假日 (端午 2026-06-19 周五) 即便是工作日也判非交易日
// ---------------------------------------------------------------------------
console.log('[4] 端午 2026-06-19 (周五但放假)...');
assert(
  isAShareTradeDay(sh('2026-06-19', '10:00')) === false,
  '端午 2026-06-19 应判非交易日'
);
assert(
  (explainNonTradeDay(sh('2026-06-19', '10:00')) || '').includes('节假日'),
  '端午 explain 应含 "节假日"'
);

// ---------------------------------------------------------------------------
// [5] 跨年边界
// ---------------------------------------------------------------------------
console.log('[5] 跨年边界...');
// 2026-01-01 周四元旦节
assert(isAShareTradeDay(sh('2026-01-01', '10:00')) === false, '2026-01-01 元旦 应非交易日');
// 2026-12-31 周四, 非节假日 (元旦在 2027-01-01 — 2027 节假日表为空, 不影响 2026)
assert(isAShareTradeDay(sh('2026-12-31', '10:00')) === true, '2026-12-31 周四 应是交易日');
// 2025-12-31 周三, 节假日表未含, 应判交易日 (周三 != 周末)
assert(isAShareTradeDay(sh('2025-12-31', '10:00')) === true, '2025-12-31 周三 应是交易日');

// ---------------------------------------------------------------------------
// [6] 跨月边界
// ---------------------------------------------------------------------------
console.log('[6] 跨月边界...');
assert(isAShareTradeDay(sh('2026-05-31', '23:59')) === false, '2026-05-31 周日 应非交易日');
assert(isAShareTradeDay(sh('2026-06-01', '00:00')) === true, '2026-06-01 周一 应交易日');
assert(isAShareTradeDay(sh('2026-04-30', '17:00')) === true, '2026-04-30 周四 应交易日');
// 2026-04-30 周四 → 五一前一天, 4 月 30 不在 holiday 表 (五一从 5.1 开始)
assert(isAShareTradeDay(sh('2026-05-01', '10:00')) === false, '2026-05-01 应非交易日 (五一)');

// ---------------------------------------------------------------------------
// [7] 闰年: 2024-02-29 (周四, 闰年最后一天)
// ---------------------------------------------------------------------------
console.log('[7] 闰年 2024-02-29 周四 (节假日表无 2024 数据, 周四应判交易日)...');
assert(
  isAShareTradeDay(sh('2024-02-29', '10:00')) === true,
  '2024-02-29 闰年周四 应判交易日'
);
// 2024-02-29 16:00 旧 bug 会漂成周五, 但周五也是工作日 — 用周五 2024-03-01 作对照
assert(
  isAShareTradeDay(sh('2024-02-29', '23:59')) === true,
  '2024-02-29 23:59 闰年周四夜间 应判交易日 (旧 bug 会漂成周五但同样是工作日)'
);

// ---------------------------------------------------------------------------
// [8] ISO date 字符串入参与 Date 入参一致
// ---------------------------------------------------------------------------
console.log('[8] ISO 字符串 vs Date 入参一致性...');
assert(
  isAShareTradeDay('2026-06-26') === isAShareTradeDay(sh('2026-06-26', '00:00')),
  'ISO string 2026-06-26 与 Date 一致'
);
assert(
  isAShareTradeDay('2026-06-27') === false,
  'ISO string 2026-06-27 周六 应非交易日'
);
assert(
  isAShareTradeDay('2026-06-19') === false,
  'ISO string 2026-06-19 端午 应非交易日'
);

// ---------------------------------------------------------------------------
// [9] 跨时区 host 模拟: 用 +00:00 (UTC) 输入也应得到正确的 Asia/Shanghai 判定
// ---------------------------------------------------------------------------
console.log('[9] 跨时区 host 模拟 (输入 UTC 时刻)...');
// 周五 2026-06-26 17:10 CST = 周五 09:10 UTC → 应判周五 (工作日)
assert(
  isAShareTradeDay(new Date('2026-06-26T09:10:00Z')) === true,
  '2026-06-26 09:10 UTC (= 周五 17:10 CST) 应判交易日'
);
// 周五 2026-06-26 23:59 CST = 周五 15:59 UTC → 应判周五
assert(
  isAShareTradeDay(new Date('2026-06-26T15:59:00Z')) === true,
  '2026-06-26 15:59 UTC (= 周五 23:59 CST) 应判交易日'
);
// 周六 2026-06-27 00:00 CST = 周五 16:00 UTC → 应判周六 (非交易日!)
assert(
  isAShareTradeDay(new Date('2026-06-26T16:00:00Z')) === false,
  '2026-06-26 16:00 UTC (= 周六 00:00 CST) 应判非交易日'
);

// ---------------------------------------------------------------------------
// 输出汇总
// ---------------------------------------------------------------------------
console.log(`\n${pass} passed, ${fail} failed.`);
if (fail > 0) {
  console.error(`\nFAILURES:\n${failures.map(f => `  - ${f}`).join('\n')}`);
  process.exit(1);
} else {
  console.log('OK all tradingCalendar timezone regression tests passed.');
  process.exit(0);
}
