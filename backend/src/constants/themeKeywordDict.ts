export interface ThemeMatch {
  industry: string;
  matched_keywords: string[];
  hit_count: number;
}

/**
 * 关键词兜底分类: 在 title + summary 里数每个 industry 命中的关键词, 返回命中最多者。
 * 无命中返回 null (调用方据此判定"未分类", 不 fan-out)。
 */
export function matchTheme(title: string, summary?: string): ThemeMatch | null {
  const hay = `${title || ''} ${summary || ''}`;
  if (!hay.trim()) return null;
  let best: ThemeMatch | null = null;
  for (const [industry, keywords] of Object.entries(THEME_KEYWORD_DICT)) {
    const matched: string[] = [];
    for (const kw of keywords) {
      if (hay.includes(kw)) matched.push(kw);
    }
    if (matched.length && (!best || matched.length > best.hit_count)) {
      best = { industry, matched_keywords: matched, hit_count: matched.length };
    }
  }
  return best;
}
